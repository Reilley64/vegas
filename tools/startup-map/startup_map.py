#!/usr/bin/env python3
"""Generate the startup and blocker map from its checked-in input.

usage: startup_map.py [--input MAP_JSON] [--readme README_MD] [--doc DOC_MD] [--check]

Reads map.json beside this script, validates it, and writes the Mermaid
overview between the markers in README.md and the detailed page
docs/startup-map.md. With --check it writes nothing and fails when either
file differs from what it would write. README.md in this directory says what
the input holds and what is validated.
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

BEGIN = "<!-- startup-map:begin (generated by tools/startup-map; do not edit) -->"
END = "<!-- startup-map:end -->"

# Node kinds in the order of their subgraphs, with the subgraph titles.
KINDS = [
    ("setup-step", "Setup"),
    ("startup-step", "Accepted startup steps"),
    ("winmain-statement", "WinMain statements main skips"),
    ("boot-body", "Boot bodies"),
    ("contract", "Contracts"),
    ("gate", "Gates"),
    ("ticket", "Tickets"),
]
STATES = {
    "accepted": "The snapshot commit has it, and the evidence of its tier covers it.",
    "in-review": "Its work is written and under review. The snapshot commit does not have it.",
    "in-progress": "Its ticket is in progress in the tracker. The snapshot commit does not have all of its work.",
    "ready": "Work on it can start now, because no `requires` or `blocks` edge makes it need an unfinished node.",
    "waiting": "It waits on a named contract, ruling, owner or ticket.",
    "blocked": "It requires nodes that are not done, and it cannot be done before they are.",
    "unknown": "No source records a route or an owner for it.",
}
# The tracker's states, as it names them, and the state each gives a node that takes its
# state from the tracker. None gives ready when no requires or blocks edge makes the node
# need an unfinished node, and waiting otherwise. The tracker's Won't fix is not in the set.
TRACKER_STATES = {
    "Needs triage": None,
    "Needs info": None,
    "Ready for agent": None,
    "Ready for human": None,
    "In progress": "in-progress",
    "In review": "in-review",
    "Done": "accepted",
}
# The states of a node without a tracker state. Only the repository shows them.
REPOSITORY_STATES = ("accepted", "waiting", "blocked", "unknown")
# Evidence tiers. Each names a distinct kind of evidence; they are not a scale and never merged.
TIERS = [
    ("curated", "A person stated it, and no machine check proves it."),
    ("source", "The source shows it, or a compiler's reading of the declarations does."),
    ("forced-link", "The forced link of every archive member shows it. That link says nothing about what a running "
                    "program reaches."),
    ("object", "An object-level proof shows it."),
    ("lazy-link", "The ordinary, lazy link of a real executable shows it."),
    ("object-check", "A standing `objects.*` or `archive.*` check shows it."),
    ("host-test", "A host test shows it."),
    ("windows-ci-test", "A test in the Windows CI job shows it."),
    ("windows-executed", "A real run on Windows shows it. The private runs on an actual input count."),
]
EDGE_KINDS = {
    "requires": "The source node needs the target node first. This is a real blocker.",
    "blocks": "The target node cannot finish before the source, a contract or ticket, does.",
    "calls": "The source refers to the target in code, for example by a call. These edges may form cycles.",
    "estimated-unlock": "A model estimates what finishing the source opens in the target. It is never a measurement.",
}
PROVENANCES = ("measured", "curated", "modelled")
# Kinds of report an edge may cite. An estimate cites a model and nothing else, and only an estimate
# is modelled.
BASIS_KINDS = ("recipe", "source", "object-check", "link", "census", "host-test", "windows-ci", "windows-run")

ID = re.compile(r"^[a-z][a-z0-9_]*$")
VEGAS = re.compile(r"^VEGAS-[0-9]+$")
DATE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$")
FULL_SHA = re.compile(r"^[0-9a-f]{40}$")
SHORT_SHA = re.compile(r"^[0-9a-f]{9,40}$")
# Text that goes into Mermaid: no quotes, brackets, pipes or angle brackets.
LABEL = re.compile(r"^[A-Za-z0-9 .,:;()'+/_=*#&-]+$")
# A node label that Mermaid's markdown strings would read as the start of a list or a heading.
LIST_START = re.compile(r"^\s*([0-9]+[.)]|[-+*#>])\s")
# A word that an estimate's row never prints, because no estimate is measured.
MEASURED = re.compile(r"\bmeasured\b", re.IGNORECASE)
FORBIDDEN = [
    ("a URL", re.compile(r"[A-Za-z][A-Za-z0-9+.-]*://")),
    ("a tracker host", re.compile(r"plane\.so", re.IGNORECASE)),
    ("a home path", re.compile(r"/Users/|/home/|[A-Za-z]:\\\\?Users|~/")),
    ("an e-mail address", re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}")),
    ("an IPv4 address", re.compile(r"(?<![0-9.])((25[0-5]|2[0-4][0-9]|1?[0-9]?[0-9])\.){3}"
                                   r"(25[0-5]|2[0-4][0-9]|1?[0-9]?[0-9])(?![0-9]|\.[0-9])")),
    ("a temporary path", re.compile(r"/tmp/|/private/|/var/folders")),
    ("a uuid-like id", re.compile(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}")),
]
NODE_FIELDS = {"id", "label", "kind", "state", "tier", "vegas", "tracker_state", "source", "detail"}
EDGE_FIELDS = {"from", "to", "kind", "provenance", "basis", "estimate"}
MEASUREMENT_FIELDS = {"label", "value", "command", "commit", "date", "tier"}
TOP_FIELDS = {"snapshot", "nodes", "edges", "measurements", "coverage", "limitations"}
SNAPSHOT_FIELDS = {"source_commit", "evidence_date", "ticket_states_date"}


def forbidden(text):
    """Problems for each forbidden pattern found in the raw input text."""
    return ["the input contains " + name for name, pattern in FORBIDDEN if pattern.search(text)]


def _fields(where, item, allowed, required, problems):
    if not isinstance(item, dict):
        problems.append(where + " is not an object")
        return False
    for key in sorted(set(item) - allowed):
        problems.append(where + " has the unsupported field " + key)
    for key in required:
        if key not in item:
            problems.append(where + " lacks " + key)
    return all(key in item for key in required)


def _text(where, value, problems, pattern=None):
    if not isinstance(value, str) or not value.strip():
        problems.append(where + " is empty or not text")
    elif pattern is not None and not pattern.match(value):
        problems.append(where + " has a character the map does not allow: " + value)


def _basis(where, basis, kinds, problems):
    if not _fields(where, basis, {"kind", "ref"}, ("kind", "ref"), problems):
        return
    if basis["kind"] not in kinds:
        problems.append(where + " has the unsupported kind " + str(basis["kind"]))
    _text(where + " ref", basis["ref"], problems)


def prerequisites(edges):
    """(needer, needed) pairs of the requires and blocks edges, in edge order."""
    pairs = []
    for edge in edges:
        if edge["kind"] == "requires":
            pairs.append((edge["from"], edge["to"]))
        elif edge["kind"] == "blocks":
            pairs.append((edge["to"], edge["from"]))
    return pairs


def cycle(nodes, edges):
    """One cycle of the requires and blocks edges, needer to needed, as a list of ids, or None."""
    after = {node: [] for node in nodes}
    for needer, needed in prerequisites(edges):
        after[needer].append(needed)
    colour = {node: 0 for node in nodes}
    for start in nodes:
        if colour[start]:
            continue
        stack, path = [(start, iter(after[start]))], [start]
        colour[start] = 1
        while stack:
            node, rest = stack[-1]
            nxt = next(rest, None)
            if nxt is None:
                colour[node] = 2
                stack.pop()
                path.pop()
            elif colour[nxt] == 1:
                return path[path.index(nxt):] + [nxt]
            elif colour[nxt] == 0:
                colour[nxt] = 1
                stack.append((nxt, iter(after[nxt])))
                path.append(nxt)
    return None


def validate(data):
    """Every problem of the parsed input, in input order. Empty when it is valid."""
    problems = []
    if not _fields("the input", data, TOP_FIELDS, sorted(TOP_FIELDS), problems):
        return problems
    snap = data["snapshot"]
    if _fields("snapshot", snap, SNAPSHOT_FIELDS, sorted(SNAPSHOT_FIELDS), problems):
        if not FULL_SHA.match(str(snap["source_commit"])):
            problems.append("snapshot source_commit is not a full commit id")
        for key in ("evidence_date", "ticket_states_date"):
            if not DATE.match(str(snap[key])):
                problems.append("snapshot " + key + " is not a date")
    kinds = {kind for kind, _ in KINDS}
    tiers = {tier for tier, _ in TIERS}
    ids = []
    for index, node in enumerate(data["nodes"]):
        where = "node " + str(node.get("id", index)) if isinstance(node, dict) else "node " + str(index)
        if not _fields(where, node, NODE_FIELDS, ("id", "label", "kind", "state", "tier", "source"), problems):
            continue
        if not isinstance(node["id"], str) or not ID.match(node["id"]):
            problems.append(where + " has an id that is not lower case letters, digits and _")
        elif node["id"] in ids:
            problems.append(where + " is defined twice")
        ids.append(node["id"])
        _text(where + " label", node["label"], problems, LABEL)
        if isinstance(node["label"], str) and LIST_START.match(node["label"]):
            problems.append(where + " label starts like a Mermaid list item or heading: " + node["label"])
        if node["kind"] not in kinds:
            problems.append(where + " has the unsupported kind " + str(node["kind"]))
        if node["state"] not in STATES:
            problems.append(where + " has the unsupported state " + str(node["state"]))
        elif node["kind"] == "startup-step" and node["state"] != "accepted":
            problems.append(where + " is a startup step of main that is not accepted")
        if node["tier"] not in tiers:
            problems.append(where + " has the unsupported tier " + str(node["tier"]))
        if "vegas" in node and not VEGAS.match(str(node["vegas"])):
            problems.append(where + " has a ticket key that is not VEGAS-<number>")
        if node["kind"] == "ticket" and "vegas" not in node:
            problems.append(where + " is a ticket without a VEGAS key")
        if "tracker_state" in node:
            if node["tracker_state"] not in TRACKER_STATES:
                problems.append(where + " has the unsupported tracker state " + str(node["tracker_state"]))
            if "vegas" not in node:
                problems.append(where + " has a tracker state but no VEGAS key")
            if node["kind"] == "gate":
                problems.append(where + " is a gate with a tracker state; a gate takes its state from the repository")
        else:
            if node["kind"] == "ticket":
                problems.append(where + " is a ticket without a tracker state")
            if node["state"] in STATES and node["state"] not in REPOSITORY_STATES:
                problems.append(where + " is " + node["state"] + " without a tracker state; the repository shows only "
                                + ", ".join(REPOSITORY_STATES))
        _text(where + " source", node["source"], problems)
        if "detail" in node:
            _text(where + " detail", node["detail"], problems)
    known = set(ids)
    edges = []
    seen = set()
    for index, edge in enumerate(data["edges"]):
        where = "edge " + str(index + 1)
        if not _fields(where, edge, EDGE_FIELDS, ("from", "to", "kind", "provenance", "basis"), problems):
            continue
        where += " (" + str(edge["from"]) + " " + str(edge["kind"]) + " " + str(edge["to"]) + ")"
        good = True
        for end in ("from", "to"):
            if edge[end] not in known:
                problems.append(where + " names the unknown node " + str(edge[end]))
                good = False
        if edge["from"] == edge["to"]:
            problems.append(where + " points at its own source")
            good = False
        if edge["kind"] not in EDGE_KINDS:
            problems.append(where + " has the unsupported kind " + str(edge["kind"]))
            good = False
        key = (str(edge["from"]), str(edge["kind"]), str(edge["to"]))
        if key in seen:
            problems.append(where + " is given twice")
        seen.add(key)
        estimate = edge["kind"] == "estimated-unlock"
        if edge["provenance"] not in PROVENANCES:
            problems.append(where + " has the unsupported provenance " + str(edge["provenance"]))
        elif estimate and edge["provenance"] != "modelled":
            problems.append(where + " is an estimate whose provenance is not modelled")
        elif not estimate and edge["provenance"] == "modelled":
            problems.append(where + " is modelled but is not an estimated-unlock edge")
        if estimate and MEASURED.search(json.dumps(edge)):
            problems.append(where + " is an estimate that uses the word measured")
        _basis(where + " basis", edge["basis"], ("model",) if estimate else BASIS_KINDS, problems)
        if estimate and "estimate" not in edge:
            problems.append(where + " lacks estimate")
        elif estimate:
            if _fields(where + " estimate", edge.get("estimate"), {"value", "unit", "basis"},
                       ("value", "unit", "basis"), problems):
                value = edge["estimate"]["value"]
                if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
                    problems.append(where + " estimate value is not a positive whole number")
                _text(where + " estimate unit", edge["estimate"]["unit"], problems, LABEL)
                _text(where + " estimate basis", edge["estimate"]["basis"], problems)
        elif "estimate" in edge:
            problems.append(where + " carries an estimate but is not an estimated-unlock edge")
        if good:
            edges.append(edge)
    found = cycle(ids, edges) if known else None
    if found:
        problems.append("the requires and blocks edges form a cycle: " + " -> ".join(found))
    states = {node["id"]: node.get("state") for node in data["nodes"] if isinstance(node, dict) and "id" in node}
    unfinished = set()
    for needer, needed in prerequisites(edges):
        if states[needed] != "accepted":
            unfinished.add(needer)
        if states[needer] in ("accepted", "ready") and states[needed] != "accepted":
            problems.append("node " + needer + " is " + states[needer] + " but needs " + needed
                            + ", which is " + str(states[needed]))
    for node in data["nodes"]:
        if not isinstance(node, dict) or node.get("tracker_state") not in TRACKER_STATES:
            continue
        wanted = TRACKER_STATES[node["tracker_state"]]
        if wanted is None:
            wanted = "waiting" if node.get("id") in unfinished else "ready"
        if node.get("state") != wanted:
            problems.append("node " + str(node.get("id")) + " has the tracker state " + node["tracker_state"]
                            + ", which gives " + wanted + ", but is " + str(node.get("state")))
    for index, item in enumerate(data["measurements"]):
        where = "measurement " + str(index + 1)
        if not _fields(where, item, MEASUREMENT_FIELDS, sorted(MEASUREMENT_FIELDS), problems):
            continue
        for key in ("label", "value", "command"):
            _text(where + " " + key, item[key], problems)
        if not SHORT_SHA.match(str(item["commit"])):
            problems.append(where + " commit is not a commit id")
        if not DATE.match(str(item["date"])):
            problems.append(where + " date is not a date")
        if item["tier"] not in tiers and item["tier"] != "model":
            problems.append(where + " has the unsupported tier " + str(item["tier"]))
    for key in ("coverage", "limitations"):
        for index, line in enumerate(data[key]):
            _text(key + " " + str(index + 1), line, problems)
    return problems


def _short(sha):
    return sha[:9]


def _class(name):
    return name.replace("-", "_")


def node_text(node):
    """The node's label with its state, tier and key, as the diagram shows it."""
    parts = [node["state"].upper(), node["tier"]]
    if "vegas" in node:
        parts.append(node["vegas"] + (" " + node["tracker_state"] if "tracker_state" in node else ""))
    return node["label"] + "<br/>" + ", ".join(parts)


def edge_line(edge):
    """One Mermaid edge. Arrows run from what is needed to what needs it."""
    curated = edge["provenance"] == "curated"
    if edge["kind"] == "requires":
        start, end = edge["to"], edge["from"]
        arrow = "-.->" if curated else "-->"
        return "  " + start + " " + arrow + " " + end
    if edge["kind"] == "estimated-unlock":
        label = "estimate of " + str(edge["estimate"]["value"]) + " " + edge["estimate"]["unit"]
        return "  " + edge["from"] + ' -. "' + label + '" .-> ' + edge["to"]
    label = edge["kind"]
    if curated:
        return "  " + edge["from"] + ' -. "' + label + '" .-> ' + edge["to"]
    arrow = "==>" if edge["kind"] == "blocks" else "-->"
    return "  " + edge["from"] + " " + arrow + "|" + label + "| " + edge["to"]


ARROWS = ("An unlabelled arrow points from what is needed to what needs it. A `blocks` arrow starts at the "
          "blocker, a `calls` arrow at the caller and an `estimate` arrow at the work.")

COLOURS = {
    "accepted": "fill:#d8f0d8,stroke:#2e7d32,color:#000",
    "in-review": "fill:#dbe9f8,stroke:#1f5fa8,color:#000",
    "in-progress": "fill:#e6dcf5,stroke:#5e35b1,color:#000",
    "ready": "fill:#fff4c2,stroke:#a07800,color:#000",
    "waiting": "fill:#ffe2c4,stroke:#c25e00,color:#000",
    "blocked": "fill:#f8d4d4,stroke:#b71c1c,color:#000",
    "unknown": "fill:#e8e8e8,stroke:#616161,color:#000",
}


def mermaid(data):
    """The Mermaid flowchart of every node and edge."""
    lines = ["```mermaid", "flowchart TB"]
    for kind, title in KINDS:
        members = [node for node in data["nodes"] if node["kind"] == kind]
        if not members:
            continue
        lines.append("  subgraph " + _class(kind) + '["' + title + '"]')
        for node in members:
            lines.append("    " + node["id"] + '["' + node_text(node) + '"]')
        lines.append("  end")
    lines.extend(edge_line(edge) for edge in data["edges"])
    for state in STATES:
        members = [node["id"] for node in data["nodes"] if node["state"] == state]
        if members:
            lines.append("  classDef " + _class(state) + " " + COLOURS[state])
            lines.append("  class " + ",".join(members) + " " + _class(state))
    curated = [node["id"] for node in data["nodes"] if node["tier"] == "curated"]
    if curated:
        lines.append("  classDef curated stroke-dasharray:6 4")
        lines.append("  class " + ",".join(curated) + " curated")
    lines.append("```")
    return "\n".join(lines)


def readme_block(data):
    """The generated part of README.md's section, markers included."""
    snap = data["snapshot"]
    return "\n".join([
        BEGIN,
        "",
        mermaid(data),
        "",
        "Each box shows its state in capitals, its evidence tier and its ticket. The tiers name distinct kinds of "
        "evidence. When a tracker state follows the ticket, the box takes its state from the tracker, and every other "
        "box takes its state from the repository.",
        ARROWS,
        "A dashed box or arrow is curated, which means that a person stated it and no machine check proves it. "
        "Estimate arrows are dashed too, and they are modelled counts.",
        "",
        "The map is a snapshot of `" + _short(snap["source_commit"]) + "` with evidence as of " + snap["evidence_date"]
        + ". [docs/startup-map.md](docs/startup-map.md) lists every node, edge, source and limitation.",
        "",
        END,
    ])


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def _table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    out.extend("| " + " | ".join(_cell(cell) for cell in row) + " |" for row in rows)
    return out


def edge_basis(edge):
    if edge["provenance"] == "curated":
        text = "curated: " + edge["basis"]["ref"]
    else:
        text = edge["provenance"] + ", " + edge["basis"]["kind"] + ": " + edge["basis"]["ref"]
    if edge["kind"] == "estimated-unlock":
        text = ("estimate of " + str(edge["estimate"]["value"]) + " " + edge["estimate"]["unit"] + " ("
                + edge["estimate"]["basis"] + "); " + text)
    return text


